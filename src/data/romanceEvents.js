/**
 * 節目に達したかを返す。達していなければ null。
 * @param {number} prevAff 直前の好感度
 * @param {number} nextAff 今回の好感度
 */
export function reachedMilestone(prevAff, nextAff) {
  return ROMANCE_MILESTONES.find((m) => prevAff < m.at && nextAff >= m.at) || null;
}
