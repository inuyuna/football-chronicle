// 恋愛の段階イベント。
//
// なぜ作ったか（本人指摘 2026-11-23）:
//   「恋人システムも同じようなもので、それぞれ数回ずつクリックするだけで
//     終わる詰まらない要素という感じになってしまっている。もったいない」
//
//   以前は 1回のデートで好感度+10、40で結婚だったので、4回押せば終わりだった。
//   金と精神を払うだけの「クリック消化」になっていた。
//
// どう変えたか:
//   - 好感度の上限を 100 にして、1回 +6 に下げた
//   - デートは月に1回まで（連打で終わらせられない）
//   - 20 / 40 / 60 / 80 / 100 の節目ごとに、相手ごとに違う出来事が起きる
//   - 節目には効果がつく。最後まで行くと結婚して PARTNER_TYPES の perk が乗る
//
//   人生1回では 100 まで到達しきらないこともある。
//   そこは「その人生ではそこまでだった」でよい（docs/GAME_DESIGN.md §2）。
//   好感度は人生ごとにゼロに戻る。相手が覚えているのは、こちらだけ。

