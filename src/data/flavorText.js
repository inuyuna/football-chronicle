/**
 * タイムリープ（第1段階転生）の演出文。
 *
 * 周回を重ねると語りが変わる。同じ文を100回読ませない、という以上に、
 * 「何度もやり直している人間がどう変質していくか」そのものが物語になる。
 * 本人の要望（2026-11-23）:
 *   「転生時のストーリー進行はしっかり用意したい」
 *
 * @param {any} s
 * @param {number} crystals 獲得する継承結晶
 */
export const timeLeapFlavor = (s, crystals) => {
  const gen = n(s.totalGenerations || s.generation);
  const cat = s.clubName || '';
  const age = n(s.age);
  const next = gen + 1;
  const tail = `\n継承結晶 ${crystals} ——　${next}周目が始まる。`;

  // 1周目 → 2周目。初めて「戻る」ことを知る
  if (gen <= 1) {
    return (
      `${age}歳。${s.playerName}のキャリアが終わる。最終所属は${cat}。\n` +
      `うまくならなかった。それだけの話だった。\n` +
      `スパイクを脱ぐとき、足の裏にグラウンドの感触が残っていた。それも数秒で消える。\n` +
      `消えないものは、頭の中にしかない。どの練習が効いて、どの選択が無駄だったか。\n` +
      `——視界が白くなる。\n` +
      `次に目を開けたとき、${s.playerName}は5歳だった。手が小さい。地面が遠い。\n` +
      `体のどこにも、さっきまでの17年ぶんが入っていない。入っているのは頭の中だけだ。\n` +
      `小学校のチャイムが聞こえる。何が起きたのかは、まだ分からない。` +
      tail
    );
  }

  // 2〜4周目。手応えが出てくる時期
  if (gen <= 4) {
    return (
      `${age}歳。${cat}で終わった。前の人生より、少しだけ遠くまで来た。\n` +
      `${gen}回目でようやく分かったことがある。才能は配られるものではなく、` +
      `どの順番で何を鍛えるかで形が決まる。\n` +
      `${s.playerName}は今回、無駄な回り道をいくつか削った。その代わり、` +
      `前は気づかなかった別の回り道に入り込んだ。\n` +
      `削れる無駄はまだある。確信がある。\n` +
      `視界が白くなる。もう驚かない。` +
      tail
    );
  }

  // 5〜9周目。作業になってくる。届かない苛立ち
  if (gen <= 9) {
    return (
      `${age}歳。${cat}。${gen}回目のキャリアが終わる。\n` +
      `引退の挨拶はもう暗記している。記者の質問も、どの順で何を聞かれるか分かる。\n` +
      `分かっていても、答えは毎回少しずつ変わる。前より遠くまで来ているからだ。\n` +
      `${s.playerName}が気にしているのは、通算${n(s.totalCareerGoals)}ゴールの数ではない。` +
      `何周かければ、あの場所に手が届くのかという一点だけだ。\n` +
      `5歳の春が、もう懐かしくもなんともない。` +
      tail
    );
  }

  // 10〜19周目。人間の限界が見えてくる
  if (gen <= 19) {
    return (
      `${age}歳。${cat}。通算${n(s.careerWins)}勝。\n` +
      `${gen}回ぶんの人生を積んだ人間が、ようやく世界の上澄みに手をかけている。\n` +
      `${s.playerName}は、自分がもう普通の意味での選手ではないことを知っている。\n` +
      `一度目の人生で必死に覚えたことを、いまは考えずにやっている。\n` +
      `考えずにやれることが増えるほど、考えなければならない領域が上に逃げていく。\n` +
      `スパイクを脱ぐ。次はもう少し上へ行ける。\n` +
      `白くなる視界のなかで、${s.playerName}は一度だけ「まだか」と思った。` +
      tail
    );
  }

  // 20周目以降。人間の形を保てなくなってくる
  return (
    `${age}歳。${cat}。${gen}回目。\n` +
    `${s.playerName}はもう、自分が何歳なのかを年齢で数えていない。\n` +
    `生きた年数の合計は、とっくに一人の人間が扱える量を超えている。\n` +
    `同じ5歳の春を${gen}回見た。同じチャイムを${gen}回聞いた。` +
    `同じ母親に${gen}回「いってらっしゃい」と言われた。\n` +
    `そのどれもが本物で、どれもがやり直される。\n` +
    `通算${n(s.totalCareerGoals)}ゴール、${n(s.careerWins)}勝。数字はもう実感と結びつかない。\n` +
    `それでも${s.playerName}は、まだ上があることだけは正確に分かる。` +
    tail
  );
};

/**
 * 第2段階以降（ハードリセット）の演出文。
 *
 * 段階ごとに「何を差し出すか」が違う。それが物語の核になる。
 *   第2段階: 積み上げた継承結晶を差し出す
 *   第3段階: 記憶そのものを差し出す（ここから超常の領域に入る）
 *   第4段階: 自分という輪郭を差し出す
 *   第5段階: 差し出すものが残っていない
 *
 * 本人の設定（2026-11-23）:
 *   「三次転生では『記憶も含めて失うことで、新たな力を得るタイムリープ』って設定でいくか。
 *     ここまでいくと超常現象とか超能力みたいなレベルでいいと思ってる」
 *
 * @param {any} s
 * @param {number} nextStage 次の段階番号（1=第2段階, 2=第3段階, ...）
 * @param {number} holy 獲得する聖杯
 */
export const ascensionFlavor = (s, nextStage, holy) => {
  const gen = n(s.totalGenerations || s.generation);
  const tail = `\n超越の聖杯 ${holy} ——`;

  if (nextStage <= 1) {
    return (
      `【第2段階転生「輪廻超越」】\n` +
      `${s.playerName}は気づいている。同じやり方では、ここから先へは行けない。\n` +
      `${gen}回の人生で積み上げたものは、確かに強さになった。` +
      `だがそれは、同じ階段を速く登るための強さでしかない。\n` +
      `階段そのものを架け替える必要がある。\n` +
      `そのためには、これまで削り出してきた継承結晶を——` +
      `何十回ぶんもの人生の、濃縮された残りかすを——すべて手放さなければならない。\n` +
      `手放した瞬間、${s.playerName}は自分がどれだけ弱かったかを思い出した。` +
      `5歳の体。何も持っていない。前よりさらに何も持っていない。\n` +
      `それでいい。器が空でなければ、新しいものは入らない。` +
      tail +
      `　ここから先は、別の競技だ。`
    );
  }

  if (nextStage === 2) {
    return (
      `【第3段階転生「星辰輪廻」】\n` +
      `差し出すものが、もう結晶では足りない。\n` +
      `${s.playerName}が今回手放すのは——記憶だ。\n` +
      `${gen}回ぶんの人生で覚えた、すべての正解。どの練習が効くか。どの年に何が起きるか。` +
      `誰が味方で、誰が壁になるか。それら全部を置いていく。\n` +
      `残るのは、言葉にならない形だけ。ボールが来る前に体が動く理由を、本人も説明できない。\n` +
      `覚えているのではない。もう、そうなっている。\n` +
      `${s.playerName}は5歳の体で目を覚まし、何も知らないまま、完璧に正しい一歩目を踏み出す。\n` +
      `これはもう、技術の話ではない。` +
      tail +
      `　人のやることではなくなった。`
    );
  }

  if (nextStage === 3) {
    return (
      `【第4段階転生「創世神転生」】\n` +
      `${s.playerName}という名前が、だんだん借り物のように感じられる。\n` +
      `${gen}回ぶんの人生を重ねた結果、どの人生の自分が本当の自分なのか、` +
      `もう判定する基準がない。\n` +
      `今回差し出すのは、その輪郭だ。\n` +
      `誰か一人であることをやめれば、同時に全員であることができる。\n` +
      `ピッチに立つとき、${s.playerName}は11人ぶんの判断を同時に持っている。` +
      `味方の次の一歩も、相手の迷いも、審判が笛を吹く0.3秒前も、` +
      `すべて同じ平面に並んで見えている。\n` +
      `試合というものが、もうスポーツの形をしていない。` +
      tail +
      `　これは創造に近い。`
    );
  }

  return (
    `【第${nextStage + 1}段階転生】\n` +
    `差し出せるものは、もう残っていない。\n` +
    `記憶も、名前も、積み上げも、${s.playerName}はすでに手放した。\n` +
    `それでもまだ上がある。上があるということだけが、唯一手放せなかったものだった。\n` +
    `${gen}回。数える意味も、とうに失われている。\n` +
    `宇宙のどこかで、誰かがボールを蹴る。その一蹴りが、別の銀河の軌道を変える。\n` +
    `${s.playerName}はそれを見て、まだ足りないと思う。` +
    tail +
    `　まだ、上がある。`
  );
};

