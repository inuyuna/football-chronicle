/**
 * タイムリープ（第1段階転生）の演出文。
 * @param {any} s
 * @param {number} crystals 獲得する継承結晶
 */
export const timeLeapFlavor = (s, crystals) => {
  const gen = n(s.totalGenerations || s.generation);
  const cat = s.clubName || '';
  return (
    `${n(s.age)}歳。${s.playerName}のキャリアが終わる。最終所属は${cat}。\n` +
    `スパイクを脱ぐとき、足の裏にグラウンドの感触が残っていた。` +
    `それも数秒で消える。消えないものは、頭の中にしかない。\n` +
    `どの練習が効いて、どの選択が無駄だったか。どのクラブに行けば伸びて、` +
    `どの年齢で何が起きるか。${gen}回ぶんの記憶が、そのまま持っていける唯一の荷物だ。\n` +
    `体は5歳に戻る。筋肉も、身長も、財布の中身も、知り合いの数も、全部ゼロからになる。` +
    `それでも、どこへ向かって走ればいいかだけは分かっている。\n` +
    `視界が白くなる。小学校のチャイムが聞こえる。\n` +
    `継承結晶 ${crystals} ——　${gen + 1}周目が始まる。`
  );
};

/**
 * 第2段階以降（ハードリセット）の演出文。
 * @param {any} s
 * @param {number} nextStage 次の段階（1〜4）
 * @param {number} holy 獲得する聖杯
 */
export const ascensionFlavor = (s, nextStage, holy) => {
  const head = [
    '輪廻超越',
    '星辰輪廻',
    '創世神転生',
    '宇宙フットボール評議会'
  ][Math.min(3, Math.max(0, nextStage - 1))];

  return (
    `【第${nextStage + 1}段階転生「${head}」】\n` +
    `${s.playerName}は気づいている。同じやり方では、ここから先へは行けない。\n` +
    `${n(s.totalGenerations || s.generation)}回の人生で積み上げたものは、確かに強さになった。` +
    `だがそれは、同じ階段を速く登るための強さでしかない。\n` +
    `階段そのものを架け替える必要がある。\n` +
    `そのためには、これまで集めた継承結晶を——` +
    `何十回ぶんもの人生で削り出してきたものを——すべて手放さなければならない。\n` +
    `${s.playerName}は迷わなかった。失うのは積み上げたものであって、積み上げ方ではない。\n` +
    `世界の底が抜ける感覚があった。落ちているのか昇っているのかは分からない。\n` +
    `超越の聖杯 ${holy} ——　ここから先は、別の競技だ。`
  );
};

